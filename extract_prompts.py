# Builds the server-only prompt module from the single source of truth (the built artifact code).
import re, json
from pathlib import Path
SOURCE = Path(__file__).resolve().parent
ROOT = SOURCE.parent
OUTPUT = ROOT / 'website' / 'netlify' / 'lib'
OUTPUT.mkdir(parents=True, exist_ok=True)
SRC = (ROOT / 'the-council.html').read_text()

def grab_block(src, start_pat):
    """Return source from start_pat through its matching closing brace (skips strings/template literals)."""
    i = src.index(start_pat); j = src.index('{', i)
    depth = 0; k = j; n = len(src); stack = []  # stack of contexts: 'tpl' or '${'
    while k < n:
        c = src[k]
        top = stack[-1] if stack else None
        if top == 'tpl':
            if c == '\\': k += 2; continue
            if c == '`': stack.pop()
            elif c == '$' and src[k+1:k+2] == '{': stack.append('${'); k += 2; continue
            k += 1; continue
        if c in '"\'':
            q = c; k += 1
            while src[k] != q:
                if src[k] == '\\': k += 1
                k += 1
            k += 1; continue
        if c == '/' and src[k+1:k+2] == '/':
            k = src.index('\n', k); continue
        if c == '`': stack.append('tpl'); k += 1; continue
        if c == '{':
            if top == '${': stack.append('{')
            else: depth += 1
        elif c == '}':
            if top == '${': stack.pop()
            elif top == '{': stack.pop()
            else:
                depth -= 1
                if depth == 0: return src[i:k+1]
        k += 1
    raise ValueError(start_pat)

def grab_line(src, start_pat):
    i = src.index(start_pat); return src[i:src.index('\n', i)]

parts = []
parts.append(grab_block(SRC, 'const MODES = [').rstrip() if False else None)
# MODES is an array literal: grab through matching ']'
i = SRC.index('const MODES = ['); j = SRC.index('\n];', i); parts[0] = SRC[i:j+3]
for pat in ['const modeOf =', 'const langName =', 'const LEN_RULE =', 'const STYLE_RULE =']:
    parts.append(grab_line(SRC, pat))
for pat in ['function latestStances(s)', 'function transcriptFor(s', 'function personaCard(p, s)', 'function contributionPrompt(s, seat)', 'function synthesisPrompt(s)']:
    parts.append(grab_block(SRC, pat))
# the council-picking prompt lives inside pickWithAI: lift its template literal into its own function
pk = grab_block(SRC, 'async function pickWithAI(')
m = re.search(r'const cat = [\s\S]*?\n  const prompt = (`[\s\S]*?`);\n', pk)
pick = 'function pickPrompt({ q, ctx, topic, goal, count, lang, skip = [] }){\n' + m.group(0).replace('const prompt = ', 'return ').replace('(window.COUNCIL_SKIP || [])', 'skip').rstrip() + '\n}'
assert 'window.' not in pick
parts.append(pick)

header = '''// AUTO-GENERATED by extract_prompts.py from the app source — do not edit by hand.
// Server-only: these prompts are never sent to the browser.
import DATA from "./personas.json" with { type: "json" };
__TOPERSONA__
const PERSONAS = DATA.P.map(toPersona);
const BY_ID = new Map([...(DATA.R || []).map(r => ({ ...toPersona(r), retired: true })), ...PERSONAS].map(p => [p.id, p]));
const personaOf = (s, id) => BY_ID.get(id) || (s.customs || []).find(c => c.id === id);
const seatPeople = s => s.seats.map(id => personaOf(s, id)).filter(Boolean);
const t = (en) => en;
'''
header = header.replace('__TOPERSONA__', SRC[SRC.index('const toPersona = '):SRC.index('const PERSONAS = D.P.map(toPersona);')].strip())
body = header + '\n'.join(parts) + '\nexport { pickPrompt, contributionPrompt, synthesisPrompt, BY_ID, PERSONAS };\n'
(OUTPUT / 'prompts.mjs').write_text(body)
data = json.loads((SOURCE / 'data.json').read_text())
(OUTPUT / 'personas.json').write_text(json.dumps({'P': data['P'], 'R': data.get('R', [])}, ensure_ascii=False))
print('prompts.mjs', len(body), 'personas', len(data['P']), 'retired', len(data.get('R', [])))
